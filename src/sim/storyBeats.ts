function createBeat(
  id: string,
  scene: string,
  trigger: TriggerKind,
  speaker: SpeakerId,
  channel: 'inPerson' | 'radio' | 'ui',
  text: string,
  explicitSpeech?: string,
  alertLevel?: 'notice' | 'watch' | 'warning',
  variantGroup?: string,
): StoryBeat {
  const speech = explicitSpeech || normalizeForSpeech(text);
  const lint = validateSpeechLint(speech);
  if (!lint.valid) {
    throw new Error(`Lint failure in beat ${id}: forbidden character '${lint.match}' in speech "${speech}"`);
  }
  return {
    id,
    scene,
    trigger,
    speaker,
    channel,
    text,
    speech,
    alertLevel,
    variantGroup,
    maxLines: 2,
  };
}

